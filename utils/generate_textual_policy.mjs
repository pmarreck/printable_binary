// Freeze the Unicode policy, rather than inheriting a compiler's evolving tables.
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
assert.equal(process.versions.unicode, '16.0', 'textual v1 requires the pinned Unicode 16.0 generator');
const sensitive = /[\p{Cc}\p{Cf}\p{White_Space}]/u;
const ranges = [];
let start = null;
for (let cp = 0; cp <= 0x110000; cp++) {
	const yes = cp < 0x110000 && ![0x20, 0x200c, 0x200d].includes(cp) && sensitive.test(String.fromCodePoint(cp));
	if (yes && start === null) start = cp;
	if (!yes && start !== null) { ranges.push([start, cp - 1]); start = null; }
}
const args = process.argv.slice(2);
const zig = args[0] === '--zig';
if (zig) args.shift();
const source = '//! Frozen Unicode 16.0 Cc/Cf/White_Space, except SPACE, ZWNJ and ZWJ.\n' +
	'//! Generated by utils/generate_textual_policy.mjs; changing v1 policy needs explicit format review.\n' +
	(zig ? 'pub const sensitive_ranges = [_][2]u21{\n' : 'pub(crate) const SENSITIVE_RANGES: &[(u32, u32)] = &[\n') +
	ranges.map(([first, last]) => zig
		? `\t.{ 0x${first.toString(16)}, 0x${last.toString(16)} },\n`
		: `\t(0x${first.toString(16)}, 0x${last.toString(16)}),\n`).join('') + (zig ? '};\n' : '];\n');
if (args.length === 2 && args[0] === '--check') {
	assert.equal(readFileSync(args[1], 'utf8'), source, 'frozen textual policy differs from the pinned Unicode oracle');
	console.log('PASS: frozen textual v1 Unicode policy matches the independent Unicode 16.0 oracle');
} else {
	assert.equal(args.length, 0, 'usage: generate_textual_policy.mjs [--zig] [--check FILE]');
	process.stdout.write(source);
}
